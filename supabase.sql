create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin'))
);
alter table public.user_roles enable row level security;

alter table public.loans add column if not exists user_id uuid references auth.users(id);
create index if not exists loans_user_id_idx on public.loans(user_id);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = (select auth.uid()) and role = 'admin'
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated, anon;

-- Availability-only endpoint: other users can know whether an item is borrowed
create or replace function public.get_asset_availability()
returns table(asset_id text, is_borrowed boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select a.id, exists (
    select 1 from public.loans l
    where l.asset_id = a.id and l.returned_at is null
  ) as is_borrowed
  from public.assets a;
$$;
revoke all on function public.get_asset_availability() from public;
grant execute on function public.get_asset_availability() to authenticated, anon;

-- updated_at 을 클라이언트 값이 아닌 DB 시간으로 자동 갱신
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

alter table public.assets enable row level security;
alter table public.loans enable row level security;

-- Remove existing policies so old permissive policies cannot override the new rules.
do $$
declare p record;
begin
  for p in select schemaname, tablename, policyname
           from pg_policies
           where schemaname = 'public' and tablename in ('assets','loans','user_roles')
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end $$;

-- 테이블 권한을 처음부터 다시 부여 (Supabase 기본 권한으로 열려 있는 쓰기 권한 제거)
revoke all on public.assets, public.loans, public.user_roles from anon, authenticated;

grant select on public.assets to anon, authenticated;
grant insert, update, delete on public.assets to authenticated;

-- 대여 기록: 누구나 조회, 익명 로그인 세션(authenticated)만 대여/수정.
-- 컬럼 단위로 허용해 asset_id·borrowed_at·user_id 같은 값은 등록 후 바꿀 수 없게 한다.
grant select on public.loans to anon, authenticated;
grant insert (asset_id, borrower_name, borrowed_at, due_date, memo, user_id)
  on public.loans to authenticated;
grant update (borrower_name, due_date, returned_at, memo, updated_at)
  on public.loans to authenticated;
grant delete on public.loans to authenticated;

create policy assets_public_read
  on public.assets for select to anon, authenticated
  using (true);

create policy assets_admin_manage
  on public.assets for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy loans_read_public
  on public.loans for select to anon, authenticated
  using (true);

-- 대여는 자기 세션(user_id = auth.uid())으로만 등록, 이미 반납된 상태로는 등록 불가
create policy loans_insert_own
  on public.loans for insert to authenticated
  with check (user_id = (select auth.uid()) and returned_at is null);

-- 대여 기록 수정/반납은 등록한 본인(user_id = auth.uid()) 또는 관리자만 가능
create policy loans_update_owner_or_admin
  on public.loans for update to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()))
  with check (user_id = (select auth.uid()) or (select public.is_admin()));

create policy loans_delete_admin_only
  on public.loans for delete to authenticated
  using ((select public.is_admin()));

grant usage, select on sequence public.loans_id_seq to authenticated;

-- 같은 비품의 동시 대여 방지: 트리거 대신 부분 유니크 인덱스 (동시 요청에도 안전)
drop trigger if exists loans_prevent_duplicate_active on public.loans;
drop function if exists public.prevent_duplicate_active_loan();
create unique index if not exists loans_one_active_per_asset
  on public.loans(asset_id) where returned_at is null;

-- 수리 중인 비품은 DB에서도 대여 불가
create or replace function public.check_loan_asset_available()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.assets a
    where a.id = new.asset_id and a.status = 'available'
  ) then
    raise exception '대여할 수 없는 비품입니다. (수리 중이거나 존재하지 않음)';
  end if;
  return new;
end;
$$;

drop trigger if exists loans_check_asset_available on public.loans;
create trigger loans_check_asset_available
  before insert on public.loans
  for each row execute function public.check_loan_asset_available();

drop trigger if exists loans_set_updated_at on public.loans;
create trigger loans_set_updated_at
  before update on public.loans
  for each row execute function public.set_updated_at();
