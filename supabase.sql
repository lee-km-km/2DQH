-- LabStock database schema + access-control (v1.1 security hardening)
-- Back up the database before running this script on an existing project.
-- 이미 운영 중인 DB는 이 파일 대신 security_patch.sql 을 실행하세요.

create table if not exists public.assets (
  id text primary key check (length(id) between 1 and 40),
  name text not null check (length(name) between 1 and 160),
  category text not null default '기타',
  location text not null default '',
  status text not null default 'available' check (status in ('available','maintenance')),
  note text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  asset_id text not null references public.assets(id) on update cascade,
  borrower_name text not null check (length(trim(borrower_name)) between 1 and 100),
  borrowed_at date not null default current_date,
  due_date date not null,
  returned_at date,
  memo text not null default '' check (length(memo) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id uuid references auth.users(id),
  check (due_date >= borrowed_at),
  check (returned_at is null or returned_at >= borrowed_at)
);

-- Anonymous visitors receive a Supabase anonymous-auth session. They are authenticated
-- users with a stable auth.uid(), but do not have administrator privileges by default.

