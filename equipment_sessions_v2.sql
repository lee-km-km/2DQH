-- ============================================================================
-- Phase 2: 연구장비 범용 세션 로그북 스키마 (equipment_sessions)
-- JSONB 기반 확장 파라미터 엔진: XRD, AFM, FT-IR, RAMAN, TEM, Sputter, ALD 전 기종 수용
-- ============================================================================

-- 1. 통합 연구장비 세션 로그 테이블
create table if not exists public.equipment_sessions (
  id bigint generated by default as identity primary key,
  equipment_id text not null default 'EQ-XRD-01',          -- e.g. EQ-XRD-01, EQ-AFM-01, EQ-RAMAN-01
  reservation_no text not null default '' check (length(reservation_no) <= 30),
  used_on date not null default current_date,
  start_time time not null,
  end_time time,
  duration_min integer check (duration_min between 1 and 1440),
  status text not null default 'done' check (status in ('active', 'done')),
  
  -- 연구원 및 조직 메타데이터
  user_name text not null check (length(trim(user_name)) between 1 and 100),
  professor text not null default '' check (length(professor) <= 100),
  affiliation text not null default '' check (length(affiliation) <= 100),
  
  -- 시료 메타데이터
  sample_name text not null default '' check (length(sample_name) <= 200),
  sample_count integer not null default 1 check (sample_count between 1 and 999),
  
  -- ★ Phase 2 핵심: 장비별 가변 파라미터 (XRD, AFM, TEM, ALD, Sputter 등 JSONB)
  parameters jsonb not null default '{}'::jsonb,
  
  memo text not null default '' check (length(memo) <= 1000),
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. 고속 검색 및 시계열 조회를 위한 인덱스 생성
create index if not exists idx_eq_sessions_eq_date on public.equipment_sessions (equipment_id, used_on desc, start_time desc);
create index if not exists idx_eq_sessions_status on public.equipment_sessions (status);
create index if not exists idx_eq_sessions_user on public.equipment_sessions (user_id);
create index if not exists idx_eq_sessions_parameters on public.equipment_sessions using gin (parameters);

-- 3. Row Level Security (RLS) 정책 설정 (LabStock 기존 RLS 모델 승계)
alter table public.equipment_sessions enable row level security;

grant select, insert, update, delete on public.equipment_sessions to anon, authenticated;

drop policy if exists eq_sessions_select on public.equipment_sessions;
drop policy if exists eq_sessions_insert on public.equipment_sessions;
drop policy if exists eq_sessions_update on public.equipment_sessions;
drop policy if exists eq_sessions_delete on public.equipment_sessions;

create policy eq_sessions_select on public.equipment_sessions
  for select using (true);

create policy eq_sessions_insert on public.equipment_sessions
  for insert with check (true);

create policy eq_sessions_update on public.equipment_sessions
  for update using (
    user_id = (select auth.uid()) or
    (select coalesce(public.is_admin(), false)) or
    auth.role() = 'anon'
  );

create policy eq_sessions_delete on public.equipment_sessions
  for delete using (
    user_id = (select auth.uid()) or
    (select coalesce(public.is_admin(), false))
  );

-- 4. 기존 xrd_logs 테이블 데이터가 있을 경우 자동 마이그레이션 (무손실 이전)
do $$
begin
  if exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'xrd_logs') then
    insert into public.equipment_sessions (
      equipment_id, reservation_no, used_on, start_time, end_time, duration_min, status,
      user_name, professor, affiliation, sample_name, sample_count, memo, user_id,
      parameters, created_at, updated_at
    )
    select
      'EQ-XRD-01' as equipment_id,
      coalesce(reservation_no, ''),
      used_on,
      start_time,
      end_time,
      duration_min,
      status,
      user_name,
      coalesce(professor, ''),
      coalesce(affiliation, ''),
      coalesce(sample_name, ''),
      coalesce(sample_count, 1),
      coalesce(memo, ''),
      user_id,
      jsonb_build_object(
        'chiller_start', chiller_start,
        'chiller_end', chiller_end,
        'vacuum_start', vacuum_start,
        'vacuum_end', vacuum_end,
        'xray_max_ok', xray_max_ok,
        'xray_min_ok', xray_min_ok,
        'position_ok', position_ok,
        'align', align,
        'scan_type', scan_type,
        'meas_info', meas_info
      ) as parameters,
      now(),
      now()
    from public.xrd_logs
    where not exists (
      select 1 from public.equipment_sessions where equipment_sessions.used_on = xrd_logs.used_on and equipment_sessions.start_time = xrd_logs.start_time and equipment_sessions.user_name = xrd_logs.user_name
    );
  end if;
end $$;
