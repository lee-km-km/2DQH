-- 1. 범용 연구장비 세션 테이블 (equipment_sessions) 생성
create table if not exists public.equipment_sessions (
  id bigint generated by default as identity primary key,
  equipment_id text not null default 'EQ-XRD-01',
  equipment_code text not null default 'EQUIP',
  reservation_no text not null default '',
  used_on date not null default current_date,
  start_time time not null default '10:00',
  end_time time,
  duration_min integer check (duration_min between 1 and 1440),
  status text not null default 'done' check (status in ('active', 'done')),
  
  -- 연구원 및 조직 메타데이터
  user_name text not null,
  professor text not null default '',
  affiliation text not null default '',
  
  -- 시료 및 분석 파라미터
  sample_name text not null default '',
  sample_count integer not null default 1,
  scan_type text not null default '',
  parameters jsonb not null default '{}'::jsonb,
  memo text not null default '',
  
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. HR-XRD 전용 디지털 로그북 테이블 (xrd_logs) 생성
create table if not exists public.xrd_logs (
  id bigint generated by default as identity primary key,
  reservation_no text not null default '',
  used_on date not null default current_date,
  start_time time not null default '10:00',
  end_time time,
  duration_min integer,
  status text not null default 'done' check (status in ('active', 'done')),
  
  -- XRD 장비 상태 계측값
  chiller_start numeric(4,1),
  chiller_end numeric(4,1),
  vacuum_start integer,
  vacuum_end integer,
  xray_max_ok boolean default false,
  xray_min_ok boolean default false,
  position_ok boolean default false,
  align text default 'PB',
  scan_type text default 'θ/2θ',
  
  -- 시료 및 측정 정보
  sample_name text not null default '',
  meas_info text not null default '',
  sample_count integer not null default 1,
  
  -- 연구원 및 소속
  affiliation text not null default '2DQH',
  user_name text not null,
  professor text not null default '',
  memo text not null default '',
  
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 3. 고속 조회를 위한 인덱스 생성
create index if not exists idx_eq_sessions_lookup on public.equipment_sessions (equipment_id, used_on desc);
create index if not exists idx_eq_sessions_date on public.equipment_sessions (used_on desc, start_time desc);
create index if not exists idx_xrd_logs_lookup on public.xrd_logs (used_on desc, start_time desc);

-- 4. RLS (Row Level Security) 설정 및 권한 부여
alter table public.equipment_sessions enable row level security;
alter table public.xrd_logs enable row level security;

-- 기존 정책 리셋 후 전면 권한 허용 (익명/로그인/관리자 모두 웹 및 대시보드에서 조회, 등록, 삭제 가능)
drop policy if exists "eq_sessions_all" on public.equipment_sessions;
create policy "eq_sessions_all" on public.equipment_sessions
  for all using (true) with check (true);

drop policy if exists "xrd_logs_all" on public.xrd_logs;
create policy "xrd_logs_all" on public.xrd_logs
  for all using (true) with check (true);

grant all on public.equipment_sessions to anon, authenticated, service_role;
grant usage, select on sequence public.equipment_sessions_id_seq to anon, authenticated, service_role;

grant all on public.xrd_logs to anon, authenticated, service_role;
grant usage, select on sequence public.xrd_logs_id_seq to anon, authenticated, service_role;

-- 5. Supabase Realtime (실시간 동기화) 활성화
do $$
begin
  if not exists (
    select 1 from pg_publication_tables 
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'equipment_sessions'
  ) then
    alter publication supabase_realtime add table public.equipment_sessions;
  end if;

  if not exists (
    select 1 from pg_publication_tables 
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'xrd_logs'
  ) then
    alter publication supabase_realtime add table public.xrd_logs;
  end if;
end $$;

